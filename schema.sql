-- 1. 기존 테이블과 정책을 깔끔하게 완전히 삭제 (CASCADE로 정책도 동시 삭제)
DROP TABLE IF EXISTS orders CASCADE;

-- 2. 최신 규격으로 orders 테이블 생성
CREATE TABLE orders (
  -- 주문 고유 번호 (자동 1씩 증가하는 정수 PK)
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- 손님 이름
  customer_name TEXT NOT NULL,

  -- 손님 전화번호
  phone TEXT NOT NULL,

  -- 음료 이름
  drink TEXT NOT NULL,

  -- 음료 기본 가격 (원 단위)
  drink_price INTEGER NOT NULL DEFAULT 0,

  -- 사이즈 (S, M, L)
  size TEXT NOT NULL DEFAULT 'M',

  -- 추가 옵션 목록 (문자열 배열)
  options TEXT[] DEFAULT '{}',

  -- 수량 (1 ~ 10)
  quantity INTEGER NOT NULL DEFAULT 1,

  -- 요청사항
  request TEXT,

  -- 최종 계산 금액
  total_price INTEGER NOT NULL DEFAULT 0,

  -- 주문 접수 일시
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. 테이블 및 컬럼 설명 추가
COMMENT ON TABLE orders IS '바이브 카페 손님 주문 내역 테이블';
COMMENT ON COLUMN orders.id IS '주문 고유 번호 (자동 증가)';
COMMENT ON COLUMN orders.customer_name IS '주문자 이름';
COMMENT ON COLUMN orders.phone IS '주문자 전화번호';
COMMENT ON COLUMN orders.drink IS '주문 음료 이름';
COMMENT ON COLUMN orders.drink_price IS '음료 기본 가격';
COMMENT ON COLUMN orders.size IS '음료 사이즈 (S, M, L)';
COMMENT ON COLUMN orders.options IS '선택한 추가 옵션 목록';
COMMENT ON COLUMN orders.quantity IS '주문 수량';
COMMENT ON COLUMN orders.request IS '요청사항';
COMMENT ON COLUMN orders.total_price IS '최종 결제 금액';
COMMENT ON COLUMN orders.created_at IS '주문 접수 시간';

-- 4. RLS(행 단위 보안 정책) 설정
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

CREATE POLICY "누구나 주문 추가 가능"
  ON orders FOR INSERT TO anon, authenticated WITH CHECK (true);

CREATE POLICY "누구나 주문 목록 조회 가능"
  ON orders FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "누구나 주문 취소 가능"
  ON orders FOR DELETE TO anon, authenticated USING (true);

-- 5. 테스트용 1건 데이터 입력 (선택 사항)
